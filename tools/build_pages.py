#!/usr/bin/env python3
"""
build_pages.py — build the English sub-pages (hako/, about/, shop/, …)
from pages/*.html, wrapped in the parts every page shares with index.html.

    python3 tools/build_pages.py           # write the pages
    python3 tools/build_pages.py --check   # fail if they're out of date (CI)

index.html is the home page and the source of the shared parts: the <head>,
the access gate, the header, the sign-up form and the footer. Each file in
pages/ holds one page's own content, with a first line like

    <!-- page: {"path": "hako/", "page": "hako", "title": "…", "description": "…"} -->

Links in pages/ are written as on the home page (relative to the site root:
"assets/…", "shop/case/", "#notify"); they're rewritten for the page's
folder. "<!-- @copy:ID -->" pastes the section with that id from index.html
("no-heading" drops its label and heading). Then run tools/build-i18n.py for
the Japanese and German versions of every page.
"""
from __future__ import annotations

import argparse
import html
import json
import re
import sys
from pathlib import Path

SITE = Path(__file__).resolve().parent.parent
BANNER = "<!-- GENERATED by tools/build_pages.py from pages/{name} + index.html. Don't edit; edit those and re-run. -->\n"
URL = "https://www.hakoshop.com/"


def specs() -> list[dict]:
    """Every sub-page: its settings plus the source file name."""
    out = []
    for f in sorted((SITE / "pages").glob("*.html")):
        first = f.read_text(encoding="utf-8").split("\n", 1)[0]
        m = re.match(r"<!-- page: (\{.*\}) -->$", first)
        if not m:
            raise SystemExit(f"{f.name}: the first line must be <!-- page: {{…}} -->")
        spec = json.loads(m.group(1))
        spec["source"] = f.name
        out.append(spec)
    return out


def prefix_links(page: str, prefix: str) -> str:
    """Relative src/href (not #anchors, absolute, mailto: or data:) get `prefix`."""
    if not prefix:
        return page
    return re.sub(r'(\b(?:src|href)=")(?!https?:|#|mailto:|/|data:)([^"]*")', r"\1" + prefix + r"\2", page)


def section(home: str, sid: str, no_heading: bool) -> str:
    i = home.index(f'<section id="{sid}"')
    j = home.index("</section>", i) + len("</section>")
    s = home[i:j]
    if no_heading:
        s = re.sub(r'\s*<div class="section-label[^"]*">.*?</div>', "", s, count=1, flags=re.S)
        s = re.sub(r"\s*<h2[^>]*>.*?</h2>", "", s, count=1, flags=re.S)
    return "  " + s + "\n"


def build(spec: dict, home: str) -> str:
    body = (SITE / "pages" / spec["source"]).read_text(encoding="utf-8").split("\n", 1)[1]
    body = re.sub(r"[ \t]*<!-- @copy:([\w-]+)( no-heading)?\b.*?-->\n?",
                  lambda m: section(home, m.group(1), bool(m.group(2))), body)

    a = home.index("<!-- @main-start")
    b = home.index("<!-- @main-end -->")
    page = home[:a] + body.lstrip("\n") + "\n  " + home[b:]

    path, title, desc = spec["path"], spec["title"], spec["description"]
    esc = lambda s: html.escape(s, quote=True)
    page = page.replace('data-page="home"', f'data-page="{spec["page"]}"', 1)
    page = re.sub(r"<title>.*?</title>", f"<title>{html.escape(title)}</title>", page, count=1)
    page = re.sub(r'(<meta name="description" content=")[^"]*', lambda m: m.group(1) + esc(desc), page, count=1)
    page = re.sub(r'(<meta property="og:title" content=")[^"]*', lambda m: m.group(1) + esc(title), page, count=1)
    page = re.sub(r'(<meta property="og:description" content=")[^"]*', lambda m: m.group(1) + esc(desc), page, count=1)
    page = page.replace(f'<meta property="og:url" content="{URL}" />', f'<meta property="og:url" content="{URL}{path}" />', 1)
    page = page.replace(f'<link rel="canonical" href="{URL}" />', f'<link rel="canonical" href="{URL}{path}" />', 1)
    for lang in ("", "ja/", "de/"):
        page = page.replace(f'hreflang="{lang[:2] or "en"}" href="{URL}{lang}"', f'hreflang="{lang[:2] or "en"}" href="{URL}{lang}{path}"')
    page = page.replace(f'hreflang="x-default" href="{URL}"', f'hreflang="x-default" href="{URL}{path}"')
    # the language switcher goes to this page in the other language
    for lang in ("", "ja/", "de/"):
        page = page.replace(f'<a href="/{lang}" hreflang=', f'<a href="/{lang}{path}" hreflang=')
    # only the home page has the interactive demo
    page = re.sub(r'  <script src="assets/demo\.js[^"]*" defer></script>\n', "", page)

    page = prefix_links(page, "../" * path.count("/"))
    return page.replace("<!DOCTYPE html>\n", "<!DOCTYPE html>\n" + BANNER.format(name=spec["source"]), 1)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="exit 1 if the pages are out of date")
    args = ap.parse_args()
    home = (SITE / "index.html").read_text(encoding="utf-8")
    stale = False
    for spec in specs():
        page = build(spec, home)
        out = SITE / spec["path"] / "index.html"
        if args.check:
            if not out.exists() or out.read_text(encoding="utf-8") != page:
                print(f"{out.relative_to(SITE)} is out of date: run python3 tools/build_pages.py", file=sys.stderr)
                stale = True
        else:
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_text(page, encoding="utf-8")
            print(f"wrote {out.relative_to(SITE)}")
    sys.exit(1 if stale else 0)


if __name__ == "__main__":
    main()
