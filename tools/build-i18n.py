#!/usr/bin/env python3
"""
build-i18n.py — generate the Japanese and German pages (ja/…, de/…) from
the English ones (index.html and the pages tools/build_pages.py builds) and
tools/i18n.json.

    python3 tools/build-i18n.py           # write the pages
    python3 tools/build-i18n.py --check   # fail if they're out of date (CI)

Separate pages (not text swapped in by JavaScript) so link previews on
LINE, X, Discord etc. show the right language, and search engines index each.
Any English text in i18n.json that's no longer on the page is reported, so
translations can't go stale silently.
"""
from __future__ import annotations

import argparse
import html
import json
import re
import sys
from html.parser import HTMLParser
from pathlib import Path

SITE = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(Path(__file__).resolve().parent))
import build_pages  # noqa: E402

# Links between our own pages stay inside the language's folder; everything
# else (assets, privacy.html, …) points back up to the English site root.
PAGE_LINK = re.compile(r"^(?:\.\./)*(?:\./|" + "|".join(re.escape(s["path"]) for s in build_pages.specs()) + r")?(?:#[\w-]*)?$")
LANGS = ["ja", "de"]
BANNER = "<!-- GENERATED by tools/build-i18n.py from index.html + tools/i18n.json. Don't edit; edit those and re-run. -->\n"


def text_pattern(en: str) -> re.Pattern:
    """Match `en` as a whole text run between two tags; any whitespace in
    `en` matches any whitespace (line breaks in the source don't matter)."""
    parts = [re.escape(p) for p in en.split()]
    body = r"\s+".join(parts)
    # Allow whitespace that sits between tags (e.g. "<br/> that") to be absent or present
    body = body.replace(r">\s+", r">\s*").replace(r"\s+<", r"\s*<")
    return re.compile(r"(?<=>)(\s*)" + body + r"(\s*)(?=<)")


def relative_to_parent(page: str) -> str:
    """The language pages live one folder down: links to assets and other
    English-only files go up one more level; links to our pages don't."""
    def fix(m):
        url = m.group(2)
        if re.match(r"(?:https?:|#|mailto:|/|data:)", url) or PAGE_LINK.match(url):
            return m.group(0)
        return m.group(1) + "../" + url + '"'
    return re.sub(r'(\b(?:src|href)=")([^"]*)"', fix, page)


def build(lang: str, source: str, tr: dict, path: str = "") -> tuple[str, list[str], set]:
    """One page in one language: the page, what couldn't be translated, and
    which i18n.json entries it used."""
    missing, used = [], set()
    page = source

    head = tr["head"][lang]
    page = page.replace('<html lang="en"', f'<html lang="{lang}"', 1)
    if path:
        ph = tr.get("pages", {}).get(path, {}).get(lang)
        if not ph:
            missing.append(f"pages: {path} (title and description)")
            ph = {}
        og = {"title": ph.get("title"), "description": ph.get("description"), "og_description": ph.get("description")}
    else:
        og = head
    esc = lambda t: html.escape(t, quote=True)
    if og.get("title"):
        page = re.sub(r"<title>.*?</title>", f"<title>{html.escape(og['title'])}</title>", page, count=1)
        if path:
            page = re.sub(r'(<meta property="og:title" content=")[^"]*', lambda m: m.group(1) + esc(og["title"]), page, count=1)
    if og.get("description"):
        page = re.sub(r'(<meta name="description" content=")[^"]*', lambda m: m.group(1) + esc(og["description"]), page, count=1)
        page = re.sub(r'(<meta property="og:description" content=")[^"]*', lambda m: m.group(1) + esc(og["og_description"]), page, count=1)
    site = "https://www.hakoshop.com/"
    page = page.replace(f'<meta property="og:url" content="{site}{path}" />', f'<meta property="og:url" content="{site}{lang}/{path}" />', 1)
    page = page.replace('assets/images/og.png"', f'assets/images/og-{lang}.png"', 1)
    page = page.replace('<meta property="og:locale" content="en_US" />', f'<meta property="og:locale" content="{head["locale"]}" />', 1)
    page = page.replace(f'<link rel="canonical" href="{site}{path}" />', f'<link rel="canonical" href="{site}{lang}/{path}" />', 1)

    # Panel images are rendered per language (hako repo: deploy/build-web-images.py)
    page = page.replace("assets/images/panel/en/", f"assets/images/panel/{lang}/")
    # Photos of the device: the shot with that language on the screen where
    # there is one (assets/images/photos/<lang>/), else the English one
    page = re.sub(r"assets/images/photos/en/([\w.-]+)",
                  lambda m: f"assets/images/photos/{lang}/{m.group(1)}"
                  if (SITE / "assets/images/photos" / lang / m.group(1)).exists() else m.group(0), page)

    for n, entry in enumerate(tr["attr"]):
        if entry["en"] in page:
            used.add(("attr", n))
        page = page.replace(entry["en"], entry[lang])

    # Longest first, so "Founder Edition or the Kickstarter run?" wins over "Founder Edition"
    for n, entry in sorted(enumerate(tr["text"]), key=lambda e: -len(e[1]["en"])):
        pat = text_pattern(entry["en"])
        page, hits = pat.subn(lambda m, t=entry[lang]: m.group(1) + t + m.group(2), page)
        if hits:
            used.add(("text", n))

    strings = json.dumps(tr["strings"][lang], ensure_ascii=False, indent=2)
    page = page.replace("</head>", f"  <script>\n    window.HAKO_STRINGS = {strings};\n  </script>\n</head>", 1)
    page = relative_to_parent(page)
    page = re.sub(r"<!-- GENERATED by tools/build_pages.py[^\n]*\n", "", page)
    page = page.replace("<!DOCTYPE html>\n", "<!DOCTYPE html>\n" + BANNER, 1)
    return page, missing, used


class _Text(HTMLParser):
    """Visible text runs of a page (no script/style/code)."""
    SKIP = {"script", "style", "code", "pre", "svg"}

    def __init__(self) -> None:
        super().__init__()
        self.depth, self.runs = 0, []

    def handle_starttag(self, tag, attrs):
        if tag in self.SKIP:
            self.depth += 1

    def handle_endtag(self, tag):
        if tag in self.SKIP:
            self.depth = max(0, self.depth - 1)

    def handle_data(self, data):
        text = " ".join(data.split())
        if not self.depth and len(re.findall(r"[A-Za-z]{2,}", text)) >= 2:
            self.runs.append(text)


def text_runs(page: str) -> list[str]:
    p = _Text()
    p.feed(page)
    return p.runs


def still_english(source: str, page: str) -> list[str]:
    """English sentences copied through unchanged: new copy on index.html
    that has no entry in i18n.json yet (or brand names, which are fine)."""
    en = set(text_runs(source))
    seen, out = set(), []
    for run in text_runs(page):
        if run in en and run not in seen and run not in KEEP_ENGLISH:
            seen.add(run)
            out.append(run)
    return out


# Text that is meant to stay English on every page
KEEP_ENGLISH = {"Founder Edition", "Founder Edition ·", "mikko", "by hako", "Shop", "Sumi · Kinari · Ai · Matcha", "hako · Shop", "hako (22 × 22 × 6 cm)",
                "Mac · Intel", "hello@hakoshop.com", "hako-windows-setup.exe", "hako-macos-arm64.dmg",
                "hako-macos-x64.dmg", "hako-linux-x64.tar.gz", "hako.ankiaddon"}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="exit 1 if the pages are out of date")
    args = ap.parse_args()

    tr = json.loads((SITE / "tools/i18n.json").read_text(encoding="utf-8"))
    pages = [("", "index.html")] + [(s["path"], s["path"] + "index.html") for s in build_pages.specs()]
    stale = False
    for lang in LANGS:
        used_all, untranslated = set(), 0
        for path, src in pages:
            source = (SITE / src).read_text(encoding="utf-8")
            page, missing, used = build(lang, source, tr, path)
            used_all |= used
            for m in missing:
                print(f"[{lang}] {m}", file=sys.stderr)
            for run in still_english(source, page):
                print(f"[{lang}] still English (add it to tools/i18n.json): /{path} {run[:90]}", file=sys.stderr)
            out = SITE / lang / path / "index.html"
            if args.check:
                if not out.exists() or out.read_text(encoding="utf-8") != page:
                    print(f"{out.relative_to(SITE)} is out of date: run python3 tools/build-i18n.py", file=sys.stderr)
                    stale = True
            else:
                out.parent.mkdir(parents=True, exist_ok=True)
                out.write_text(page, encoding="utf-8")
                print(f"wrote {out.relative_to(SITE)}")
        for kind in ("attr", "text"):
            for n, entry in enumerate(tr[kind]):
                if (kind, n) not in used_all:
                    print(f"[{lang}] not found on any page (update tools/i18n.json): {kind}: {entry['en'][:70]}", file=sys.stderr)
    sys.exit(1 if stale else 0)


if __name__ == "__main__":
    main()
